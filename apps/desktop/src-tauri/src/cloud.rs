use serde::Serialize;
use serde_json::Value;
use std::{io::Write, process::{Command, Stdio}};
use tauri::AppHandle;

const KEYCHAIN_SERVICE: &str = "uk.co.good-ship.ship-check.cloud";
const KEYCHAIN_ACCOUNT: &str = "history-sync";
const CLOUD_URL: &str = "https://cloud-check.good-ship.co.uk";
const MAX_REPORT_BYTES: usize = 8 * 1024 * 1024;

#[derive(Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct CloudConnection {
    pub saved: bool,
    pub message: String,
}

#[derive(Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct CloudSyncResult {
    pub project_id: String,
    pub status: String,
    pub ingested_at: String,
    pub timeline_url: String,
}

fn entry() -> Result<keyring::Entry, String> {
    keyring::Entry::new(KEYCHAIN_SERVICE, KEYCHAIN_ACCOUNT)
        .map_err(|_| "System credential store is unavailable. No token was saved.".to_owned())
}

pub fn validate_token(token: &str) -> bool {
    token.len() == 53
        && token.starts_with("shipcheck_")
        && token[10..].bytes().all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_')
}

pub fn save_token(token: String) -> Result<CloudConnection, String> {
    if !validate_token(&token) {
        return Err("Enter a valid expiring Ship Check Cloud history:sync token.".to_owned());
    }
    // No plaintext fallback: fail closed when the OS credential store is unavailable.
    entry()?.set_password(&token)
        .map_err(|_| "Could not save your token in the operating system credential store.".to_owned())?;
    Ok(CloudConnection {
        saved: true,
        message: "Token stored securely on this device; its permissions are checked when you sync.".to_owned(),
    })
}

pub fn connection_status() -> Result<CloudConnection, String> {
    match entry()?.get_password() {
        Ok(token) if validate_token(&token) => Ok(CloudConnection {
            saved: true,
            message: "Cloud sync token saved in your system credential store. No automatic uploads.".to_owned(),
        }),
        Ok(_) => Err("Saved Cloud token is invalid. Replace it through Connect Cloud.".to_owned()),
        Err(keyring::Error::NoEntry) => Ok(CloudConnection {
            saved: false,
            message: "Not connected. Local scanning works without Cloud.".to_owned(),
        }),
        Err(_) => Err("System credential store could not be opened.".to_owned()),
    }
}

pub fn forget_token() -> Result<CloudConnection, String> {
    match entry()?.delete_credential() {
        Ok(()) | Err(keyring::Error::NoEntry) => Ok(CloudConnection {
            saved: false,
            message: "Cloud token forgotten on this device. Revoke it in your Cloud dashboard if no longer needed.".to_owned(),
        }),
        Err(_) => Err("Could not remove the token from the system credential store.".to_owned()),
    }
}

fn clean_label(name: &str) -> Option<String> {
    let trimmed = name.trim();
    if trimmed.is_empty() || trimmed.len() > 120 || trimmed.chars().any(char::is_control) {
        None
    } else {
        Some(trimmed.to_owned())
    }
}

pub fn publish_report(app: &AppHandle, report: Value, display_name: String) -> Result<CloudSyncResult, String> {
    // Never accept an arbitrary server URL or an arbitrary command from the webview.
    // The request is generated by the bundled canonical engine from one completed report.
    if report.get("tool").and_then(|x| x.get("name")).and_then(Value::as_str) != Some("ship-check") {
        return Err("Only a completed Ship Check report can be sent to Cloud.".to_owned());
    }
    let label = clean_label(&display_name)
        .ok_or_else(|| "Enter a short project name for the Cloud history.".to_owned())?;
    let token = entry()?.get_password()
        .map_err(|_| "Connect a Cloud history:sync token before sharing a summary.".to_owned())?;
    if !validate_token(&token) {
        return Err("Stored Cloud token is invalid. Create a new history:sync token.".to_owned());
    }
    let input = serde_json::to_vec(&report)
        .map_err(|_| "Could not prepare this scan report.".to_owned())?;
    if input.len() > MAX_REPORT_BYTES {
        return Err("This report exceeds the desktop Cloud conversion limit. Use the CLI metadata sync workflow.".to_owned());
    }
    let engine = super::engine::locate_engine(app)?;
    let mut child = Command::new(engine)
        .args([
            "cloud", "publish", "-", "--cloud-url", CLOUD_URL,
            "--retention", "90-days", "--display-name", label.as_str()
        ])
        .env("SHIP_CHECK_CLOUD_TOKEN", token.as_str())
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .map_err(|_| "Could not start the local Ship Check metadata converter.".to_owned())?;
    {
        let mut stdin = child.stdin.take()
            .ok_or_else(|| "Could not send the completed report to the local converter.".to_owned())?;
        stdin.write_all(&input)
            .map_err(|_| "Could not convert the report into source-free metadata.".to_owned())?;
    }
    let output = child.wait_with_output()
        .map_err(|_| "Local Cloud conversion process did not finish.".to_owned())?;
    if !output.status.success() {
        // Don't expose potentially sensitive upstream errors or credential strings.
        let raw = String::from_utf8_lossy(&output.stderr);
        let safe = raw.replace(token.as_str(), "[redacted-token]");
        return Err(if safe.contains("403") || safe.contains("401") {
            "Cloud refused this token. Create a new history:sync token in your dashboard.".to_owned()
        } else {
            "Cloud sync did not complete. Your local scan is unchanged; check connectivity, Cloud permissions and retention settings.".to_owned()
        });
    }
    let payload: Value = serde_json::from_slice(&output.stdout)
        .map_err(|_| "Cloud responded without a valid project receipt.".to_owned())?;
    let project_id = payload.get("projectId").and_then(Value::as_str)
        .filter(|x| uuid_shape(x))
        .ok_or_else(|| "Cloud returned an invalid project receipt.".to_owned())?;
    let status = payload.get("scanStatus").and_then(Value::as_str)
        .filter(|x| matches!(x, "stored" | "duplicate" | "enriched"))
        .ok_or_else(|| "Cloud did not confirm the stored scan.".to_owned())?;
    let ingested_at = payload.get("ingestedAt").and_then(Value::as_str)
        .ok_or_else(|| "Cloud returned no scan timestamp.".to_owned())?;
    Ok(CloudSyncResult {
        project_id: project_id.to_owned(),
        status: status.to_owned(),
        ingested_at: ingested_at.to_owned(),
        timeline_url: format!("{CLOUD_URL}/dashboard/projects/{project_id}"),
    })
}

fn uuid_shape(value: &str) -> bool {
    let bytes = value.as_bytes();
    bytes.len() == 36 && bytes.iter().enumerate().all(|(i, b)| {
        if [8,13,18,23].contains(&i) { *b == b'-' }
        else { b.is_ascii_hexdigit() }
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn credential_validation_rejects_truncated_or_malformed_tokens() {
        assert!(validate_token(&format!("shipcheck_{}", "A".repeat(43))));
        assert!(!validate_token("test"));
        assert!(!validate_token(&format!("shipcheck_{}", "A".repeat(42))));
        assert!(!validate_token(&format!("shipcheck_{}\n", "A".repeat(43))));
    }

    #[test]
    fn only_safe_cloud_project_labels_are_allowed() {
        assert_eq!(clean_label("  Example  "), Some("Example".to_owned()));
        assert!(clean_label("secret\nheader").is_none());
        assert!(clean_label(&"a".repeat(121)).is_none());
    }

    #[test]
    fn rejects_invalid_cloud_project_receipts() {
        assert!(uuid_shape("aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa"));
        assert!(!uuid_shape("https://localhost/"));
    }
}
